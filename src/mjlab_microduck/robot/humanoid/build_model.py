"""Build the MuJoCo model of the STS3215 humanoid from its printable STLs.

The humanoid frame (18 DoF, ~825 mm, Feetech STS3215 servos) is generated by the
parametric SDF scripts that live next to the STLs (``humanoid_frame/src/robot.py``).
This script turns that output into what mjlab needs:

  * ``frame_joints.json``  — joint axes, origins and ranges, exported from robot.py by
    ``export_frame_joints.py`` (run it again whenever robot.py changes).
  * the STLs (stage 2, lightweight) — decimated, moved into each body's frame and
    written to ``assets/``; their volume/CoM/inertia feed the mass model.
  * ``robot_walk.xml`` and ``scene.xml`` — the robot and a flat-floor scene.

Run (from the repo root)::

    uv run --with trimesh --with fast-simplification --with scipy \\
        python src/mjlab_microduck/robot/humanoid/build_model.py \\
        --stl-dir /path/to/humanoid_frame/stl/stage2_lightweight

Conventions
-----------
* Every joint angle equals the servo's own reading (horn relative to case, about
  the horn axis, right-handed), minus its centre. Where the moving body is the
  one that holds the servo case (the shoulder roll: the case sits in the upper arm
  and the yoke is on the shoulder) the joint axis is the negated horn axis, so
  the sign still matches the servo. The runtime therefore needs no per-joint
  sign table — only a zero offset.
* Because the right-side servos are mirror images, a mirrored pose has the same
  joint angle with the OPPOSITE sign on the right (like the Microduck: e.g.
  right_hip_pitch = -left_hip_pitch). Right-side ranges are the left range
  negated and swapped.
* At q = 0 the robot is in the STL pose: legs straight, arms straight out
  sideways (T-pose). Body frames are world-aligned at q = 0 and sit on their
  joint axis, so every joint axis is a constant vector in its body frame.

Mass model (ASSUMPTIONS — the robot is not built yet; replace with weighed
values once it is): see ``MASS_MODEL`` below. The total comes out around 2.2 kg.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

# ───────────────────────────────────────────────────────────── mass model
MASS_MODEL = {
    # Printed parts: PLA/PETG solid density × the fraction of the solid a print
    # with 4 walls + 15–20 % gyroid infill actually weighs. 0.6 is a guess for
    # these thin-walled parts; screws/heat-set inserts add another 8 %.
    "print_density_g_cm3": 1.24,
    "print_fill_factor": 0.60,
    "hardware_factor": 1.08,
    # Feetech STS3215 with horns (datasheet ~55 g).
    "servo_g": 55.0,
    # Electronics (assumed models — not chosen yet):
    "compute_g": 75.0,   # Raspberry Pi 5 class board + cooler + bus adapter
    "battery_g": 185.0,  # 3S 2200 mAh LiPo (the servos are the 12 V STS3215)
    "lidar_g": 47.0,     # LD19 class 2D LiDAR
    "camera_g": 5.0,     # Pi Camera class module
    "imu_g": 10.0,       # IMU board in the pelvis (see IMU_POS)
    "wiring_g": 60.0,    # servo bus cables + power distribution, lumped in the chest
}

# STS3215 case in the servo frame (origin on the output axis, +z = horn, +x = short end).
CASE_LO = np.array([-35.2, -12.4, -15.9])
CASE_HI = np.array([10.2, 12.4, 15.9])

# The IMU lives in the pelvis (the floating base), in the sacrum behind the
# torso-yaw servo, so the policy's gravity / gyro are not rotated by the waist.
IMU_POS_MM = (-27.0, 0.0, 5.0)

# ───────────────────────────────────────────────────────────── kinematic tree
# body -> (parent, joint key in frame_joints.json, joint name)
SIDES = {"L": ("left", ""), "R": ("right", "_R")}


def tree():
    t = {"pelvis": (None, None, None)}
    for s, (side, suf) in SIDES.items():
        t[f"hip_roll_link_{s}"] = ("pelvis", "HR" + suf, f"{side}_hip_roll")
        t[f"hip_pitch_link_{s}"] = (f"hip_roll_link_{s}", "HP" + suf, f"{side}_hip_pitch")
        t[f"thigh_{s}"] = (f"hip_pitch_link_{s}", "HY" + suf, f"{side}_hip_yaw")
        t[f"shin_{s}"] = (f"thigh_{s}", "KN" + suf, f"{side}_knee")
        t[f"foot_{s}"] = (f"shin_{s}", "AN" + suf, f"{side}_ankle")
    t["chest"] = ("pelvis", "TY", "torso_yaw")
    t["head"] = ("chest", "NP", "neck_pitch")
    for s, (side, suf) in SIDES.items():
        t[f"upper_arm_{s}"] = ("chest", "SP" + suf, f"{side}_shoulder_pitch")
        t[f"elbow_link_{s}"] = (f"upper_arm_{s}", "SR" + suf, f"{side}_shoulder_roll")
        t[f"forearm_{s}"] = (f"elbow_link_{s}", "EP" + suf, f"{side}_elbow")
    return t


# Order bodies are written in (= mjlab joint / action order):
#   left leg (5), right leg (5), torso_yaw, neck_pitch, left arm (3), right arm (3)
BODY_ORDER = (
    ["pelvis"]
    + [f"{b}_L" for b in ("hip_roll_link", "hip_pitch_link", "thigh", "shin", "foot")]
    + [f"{b}_R" for b in ("hip_roll_link", "hip_pitch_link", "thigh", "shin", "foot")]
    + ["chest", "head"]
    + [f"{b}_L" for b in ("upper_arm", "elbow_link", "forearm")]
    + [f"{b}_R" for b in ("upper_arm", "elbow_link", "forearm")]
)

# STL file(s) shown on each body. Centre parts have no side suffix.
EXTRA_MESHES = {"chest": ["chest_hatch"], "head": ["head_cap"]}


def stl_name(body: str) -> str:
    return body  # pelvis, chest, head, thigh_L, ...


# ───────────────────────────────────────────────────────────── helpers
def box_inertia(mass, size):
    x, y, z = size
    return mass / 12.0 * np.diag([y * y + z * z, x * x + z * z, x * x + y * y])


class Lump:
    """Mass properties accumulated in WORLD coordinates (metres, kg)."""

    def __init__(self):
        self.items = []  # (mass, com, inertia_about_com_world)

    def add(self, m, com, I):
        self.items.append((float(m), np.asarray(com, float), np.asarray(I, float)))

    def total(self):
        M = sum(m for m, _, _ in self.items)
        c = sum(m * p for m, p, _ in self.items) / M
        I = np.zeros((3, 3))
        for m, p, Ii in self.items:
            d = p - c
            I += Ii + m * (np.dot(d, d) * np.eye(3) - np.outer(d, d))
        return M, c, I


def fmt(v, n=6):
    return " ".join(f"{x:.{n}g}" for x in np.ravel(v))


# ───────────────────────────────────────────────────────────── build
def main():
    import trimesh
    import fast_simplification

    ap = argparse.ArgumentParser()
    ap.add_argument("--stl-dir", required=True, type=Path)
    ap.add_argument("--faces", type=int, default=3000, help="faces per visual mesh")
    args = ap.parse_args()

    J = json.loads((HERE / "frame_joints.json").read_text())
    bays = J.pop("_BAYS")
    T = tree()
    mm = 1e-3

    # body origin = its joint origin (world, metres); pelvis at the hip-roll axis height.
    origin = {"pelvis": np.zeros(3)}
    joint_info = {}
    for body in BODY_ORDER[1:]:
        parent, jk, jname = T[body]
        j = J[jk]
        o = np.array(j["o"]) * mm
        R = np.array(j["R"])
        a = R[:, 2]
        base = body.rsplit("_", 1)[0] if body[-2:] in ("_L", "_R") else body
        child_is_yoke = j["yoke"] == base
        assert child_is_yoke or j["sleeve"] == base, (body, j)
        axis = a if child_is_yoke else -a
        lo, hi = j["rng"]
        if jk.endswith("_R"):
            lo, hi = -hi, -lo
        origin[body] = o
        joint_info[body] = dict(name=jname, axis=axis, range=(math.radians(lo), math.radians(hi)))

    # ── mass model
    lumps = {b: Lump() for b in BODY_ORDER}
    rho = MASS_MODEL["print_density_g_cm3"] * MASS_MODEL["print_fill_factor"] * MASS_MODEL["hardware_factor"]
    asset_dir = HERE / "assets"
    asset_dir.mkdir(exist_ok=True)
    for old in asset_dir.glob("*.stl"):
        old.unlink()
    meshes = {b: [] for b in BODY_ORDER}
    report = []
    for body in BODY_ORDER:
        for name in [stl_name(body)] + EXTRA_MESHES.get(body, []):
            m = trimesh.load(args.stl_dir / f"{name}.stl")
            if m.volume < 0:
                m.invert()
            vol_cm3 = m.volume / 1000.0
            mass = vol_cm3 * rho / 1000.0  # kg
            com = m.center_mass * mm
            # inertia of a uniform solid of this mass, about its CoM, world axes (m^2 kg)
            I = m.moment_inertia / m.volume * mass * mm * mm * 1e0
            # trimesh moment_inertia assumes density 1 in mesh units (mm): I[mm^5]; /vol -> mm^2
            lumps[body].add(mass, com, I)
            report.append((name, body, round(mass * 1000, 1)))
            # decimated visual mesh in the body frame, metres
            v, f = fast_simplification.simplify(
                m.vertices.astype(np.float32), m.faces.astype(np.int64),
                target_reduction=max(0.0, 1.0 - args.faces / len(m.faces)),
            )
            vis = trimesh.Trimesh(vertices=v * mm - origin[body], faces=f, process=True)
            vis.export(asset_dir / f"{name}.stl")
            meshes[body].append(name)

    # servos: case box at the part holding the sleeve
    servo_mass = MASS_MODEL["servo_g"] / 1000.0
    case_c = (CASE_LO + CASE_HI) / 2 * mm
    case_size = (CASE_HI - CASE_LO) * mm
    servo_geoms = {b: [] for b in BODY_ORDER}
    for body, info in joint_info.items():
        parent, jk, _ = T[body]
        j = J[jk]
        R = np.array(j["R"])
        o = np.array(j["o"]) * mm
        holder = parent if j["yoke"] == (body.rsplit("_", 1)[0] if body[-2:] in ("_L", "_R") else body) else body
        c = o + R @ case_c
        lumps[holder].add(servo_mass, c, R @ box_inertia(servo_mass, case_size) @ R.T)
        servo_geoms[holder].append((info["name"], c - origin[holder], R, case_size / 2))

    def bay_center(k):
        lo, hi = (np.array(x) * mm for x in bays[k])
        return (lo + hi) / 2, hi - lo

    for k, body, key in (("compute", "chest", "compute_g"), ("battery", "chest", "battery_g"),
                         ("lidar", "head", "lidar_g"), ("camera", "head", "camera_g")):
        c, size = bay_center(k)
        m = MASS_MODEL[key] / 1000.0
        lumps[body].add(m, c, box_inertia(m, size * 0.8))
    imu = np.array(IMU_POS_MM) * mm
    lumps["pelvis"].add(MASS_MODEL["imu_g"] / 1000.0, imu, box_inertia(MASS_MODEL["imu_g"] / 1000.0, (0.03, 0.03, 0.01)))
    wc = np.array([-0.015, 0.0, 0.13])
    lumps["chest"].add(MASS_MODEL["wiring_g"] / 1000.0, wc, box_inertia(MASS_MODEL["wiring_g"] / 1000.0, (0.05, 0.08, 0.1)))

    inertials = {b: lumps[b].total() for b in BODY_ORDER}
    total_mass = sum(v[0] for v in inertials.values())

    # ── collision geometry (primitives; meshes are visual only)
    # foot sole: flat box under heel + ball (shoe bottom is z=-470 mm)
    def foot_box(s):
        sign = 1 if s == "L" else -1
        lo = np.array([-38.0, 36.0 if s == "L" else -84.0, -470.0]) * mm
        hi = np.array([74.0, 84.0 if s == "L" else -36.0, -462.0]) * mm
        return (lo + hi) / 2 - origin[f"foot_{s}"], (hi - lo) / 2

    # every other part: an oriented bounding box of its own mesh (falls, contacts with the floor)
    obb = {}
    for body in BODY_ORDER:
        if body.startswith("foot"):
            continue
        m = trimesh.load(asset_dir / f"{stl_name(body)}.stl")
        bb = m.bounding_box_oriented
        tf = bb.primitive.transform
        ext = bb.primitive.extents / 2 * 0.92
        obb[body] = (tf[:3, 3], tf[:3, :3], ext)

    # ── write robot_walk.xml
    L = []
    w = L.append
    w('<mujoco model="sts3215_humanoid">')
    w("  <!-- GENERATED by build_model.py from the humanoid_frame STLs. Do not hand-edit:")
    w("       change robot.py / MASS_MODEL and regenerate. -->")
    w('  <compiler angle="radian" meshdir="assets" autolimits="true"/>')
    w("  <default>")
    w('    <default class="humanoid">')
    w('      <joint damping="0.85" frictionloss="0.05" armature="0.028"/>')
    w("      <!-- XML fallback PD (used with --no-bam). 12 V STS3215 on 3S (11.7 V), firmware P=32,")
    w("           per sts3215_12V_derived.json: ~27 Nm/rad, back-EMF damping ~0.85 Nm s/rad, stall ~5 Nm. -->")
    w('      <position kp="27" kv="0" forcerange="-5.0 5.0" ctrlrange="-3.2 3.2"/>')
    w('      <default class="visual"><geom type="mesh" contype="0" conaffinity="0" group="2" density="0"/></default>')
    w('      <default class="collision"><geom group="3" density="0"/></default>')
    w('      <default class="servo"><geom type="box" contype="0" conaffinity="0" group="1" density="0" rgba="0.1 0.1 0.12 1"/></default>')
    w("    </default>")
    w("  </default>")
    w("  <asset>")
    w('    <material name="shell" rgba="0.92 0.92 0.94 1" specular="0.4" shininess="0.6"/>')
    w('    <material name="accent" rgba="0.25 0.27 0.30 1"/>')
    for body in BODY_ORDER:
        for name in meshes[body]:
            w(f'    <mesh name="{name}" file="{name}.stl"/>')
    w("  </asset>")
    w("  <worldbody>")

    children = {b: [] for b in BODY_ORDER}
    for b in BODY_ORDER[1:]:
        children[T[b][0]].append(b)

    def quat_of(Rm):
        import scipy.spatial.transform as st
        x, y, z, ww = st.Rotation.from_matrix(Rm).as_quat()
        return np.array([ww, x, y, z])

    def emit(body, depth):
        ind = "  " * depth
        if body == "pelvis":
            w(f'{ind}<body name="pelvis" pos="0 0 0.49" childclass="humanoid">')
            w(f'{ind}  <freejoint name="pelvis_freejoint"/>')
        else:
            rel = origin[body] - origin[T[body][0]]
            w(f'{ind}<body name="{body}" pos="{fmt(rel)}">')
            ji = joint_info[body]
            w(f'{ind}  <joint name="{ji["name"]}" type="hinge" axis="{fmt(ji["axis"], 4)}" range="{ji["range"][0]:.5f} {ji["range"][1]:.5f}"/>')
        M, c, I = inertials[body]
        c_local = c - origin[body]
        w(f'{ind}  <inertial pos="{fmt(c_local)}" mass="{M:.5f}" fullinertia="{I[0,0]:.4e} {I[1,1]:.4e} {I[2,2]:.4e} {I[0,1]:.4e} {I[0,2]:.4e} {I[1,2]:.4e}"/>')
        for name in meshes[body]:
            mat = "accent" if name.startswith(("hip_roll", "hip_pitch", "elbow_link")) else "shell"
            w(f'{ind}  <geom class="visual" mesh="{name}" material="{mat}"/>')
        for jname, c_s, Rs, half in servo_geoms[body]:
            w(f'{ind}  <geom class="servo" name="{jname}_servo" pos="{fmt(c_s)}" quat="{fmt(quat_of(Rs))}" size="{fmt(half)}"/>')
        if body.startswith("foot"):
            s = body[-1]
            side = SIDES[s][0]
            c_f, h_f = foot_box(s)
            w(f'{ind}  <geom class="collision" name="{side}_foot_collision" type="box" pos="{fmt(c_f)}" size="{fmt(h_f)}"/>')
            site = c_f.copy()
            site[2] -= h_f[2]
            w(f'{ind}  <site group="3" name="{side}_foot" pos="{fmt(site)}" size="0.005"/>')
        else:
            p, Rb, ext = obb[body]
            w(f'{ind}  <geom class="collision" name="{body}_collision" type="box" pos="{fmt(p)}" quat="{fmt(quat_of(Rb))}" size="{fmt(ext)}"/>')
        if body == "pelvis":
            w(f'{ind}  <site group="3" name="imu" pos="{fmt(imu)}" size="0.006"/>')
        if body == "head":
            cc, _ = bay_center("camera")
            w(f'{ind}  <site group="3" name="head_camera" pos="{fmt(cc - origin["head"] + np.array([0.011, 0, 0]))}" size="0.004"/>')
            lc, _ = bay_center("lidar")
            w(f'{ind}  <site group="3" name="lidar" pos="{fmt(lc - origin["head"])}" size="0.004"/>')
        if body.startswith("forearm"):
            m = trimesh.load(asset_dir / f"{body}.stl")
            tip = m.vertices[np.argmax(np.abs(m.vertices[:, 1]))]
            w(f'{ind}  <site group="3" name="{SIDES[body[-1]][0]}_hand" pos="{fmt(np.array([0, tip[1] * 0.92, 0]))}" size="0.006"/>')
        for ch in children[body]:
            emit(ch, depth + 1)
        w(f"{ind}</body>")

    emit("pelvis", 2)
    w("  </worldbody>")
    w("  <actuator>")
    for body in BODY_ORDER[1:]:
        n = joint_info[body]["name"]
        w(f'    <position class="humanoid" name="{n}" joint="{n}"/>')
    w("  </actuator>")
    w("  <sensor>")
    w('    <framequat name="orientation" objtype="site" objname="imu"/>')
    w('    <gyro name="imu_ang_vel" site="imu"/>')
    w('    <velocimeter name="imu_lin_vel" site="imu"/>')
    w('    <accelerometer name="imu_accel" site="imu"/>')
    w('    <subtreeangmom name="root_angmom" body="pelvis"/>')
    w("  </sensor>")
    w("</mujoco>")
    (HERE / "robot_walk.xml").write_text("\n".join(L) + "\n")

    summary = {
        "total_mass_kg": round(total_mass, 3),
        "bodies": {b: dict(mass_kg=round(inertials[b][0], 4)) for b in BODY_ORDER},
        "parts": report,
        "mass_model": MASS_MODEL,
    }
    (HERE / "mass_report.json").write_text(json.dumps(summary, indent=1) + "\n")
    print(f"total mass {total_mass:.3f} kg")
    for b in BODY_ORDER:
        print(f"  {b:18s} {inertials[b][0]*1000:7.1f} g")


if __name__ == "__main__":
    main()
